// Builds docs/TRACEABILITY.md from Playwright JSON reports: requirement → acceptance criterion → test case → bug → evidence → result.
// Usage:
//   npx playwright test --reporter=json > results-main.json
//   node scripts/traceability.mjs results-main.json [results-fixes.json]
// The second report (optional) is a run of the same suite with the bugs fixed (branch `fixes`).

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const [mainReport, fixesReport] = process.argv.slice(2);
if (!mainReport) {
  console.error("Usage: node scripts/traceability.mjs <results-main.json> [results-fixes.json]");
  process.exit(1);
}

function collect(file) {
  const report = JSON.parse(readFileSync(file, "utf8"));
  const rows = new Map();
  const walk = (suite) => {
    for (const spec of suite.specs ?? []) {
      for (const t of spec.tests) {
        const meta = Object.fromEntries((t.annotations ?? []).map((a) => [a.type, a.description]));
        const status = t.results.at(-1)?.status ?? "not run";
        rows.set(meta.case_key ?? spec.title, { title: spec.title, file: `${spec.file}:${spec.line}`, tags: spec.tags ?? [], meta, status });
      }
    }
    (suite.suites ?? []).forEach(walk);
  };
  report.suites.forEach(walk);
  return { rows, stats: report.stats };
}

const main = collect(mainReport);
const fixes = fixesReport ? collect(fixesReport) : null;
const mark = (s) => (s === "passed" ? "✅ pass" : s === "failed" || s === "timedOut" ? "❌ fail" : s);
const keyOrder = (k) => k.replace(/\d+/, (n) => n.padStart(3, "0"));
const rows = [...main.rows.entries()].sort(([a], [b]) => keyOrder(a).localeCompare(keyOrder(b)));

const acs = new Map();
for (const [key, r] of rows) {
  for (const part of (r.meta.ac ?? "").split(" | ")) {
    const [id, ...text] = part.split(": ");
    if (!id) continue;
    const entry = acs.get(id) ?? { text: text.join(": "), cases: [], bugs: new Set() };
    entry.cases.push(key);
    if (r.meta.defect) entry.bugs.add(r.meta.defect.split(" ")[0]);
    acs.set(id, entry);
  }
}

const bugCell = (r) => {
  if (!r.meta.defect) return "— (control)";
  const id = r.meta.defect.split(" ")[0];
  return existsSync(join(ROOT, "evidence", id, "README.md")) ? `[${id}](../evidence/${id}/README.md)` : id;
};

const count = (rs, s) => [...rs.values()].filter((r) => r.status === s).length;
const lines = [
  "# Traceability matrix",
  "",
  "Generated by `scripts/traceability.mjs` from the Playwright JSON reports; do not edit by hand.",
  "Every test carries `case_key`, `ac`, `requirement` and `defect` annotations and tags (`@ui`/`@api`, `@P1`…`@P3`, `@AC-xx`, `@BUG-xx`, its case key), so any slice can be run with `npx playwright test --grep <tag>`.",
  "",
  "## Summary",
  "",
  `| Run | Tests | Pass | Fail |`,
  `|---|---|---|---|`,
  `| \`main\` (app as delivered, bugs open) | ${main.rows.size} | ${count(main.rows, "passed")} | ${main.rows.size - count(main.rows, "passed")} |`,
  ...(fixes ? [`| \`fixes\` branch (one commit per bug) | ${fixes.rows.size} | ${count(fixes.rows, "passed")} | ${fixes.rows.size - count(fixes.rows, "passed")} |`] : []),
  "",
  "A test that fails on `main` and passes on `fixes` proves two things: it detects its bug, and it is a valid regression test once the bug is fixed.",
  "",
  "## Acceptance criteria coverage",
  "",
  "| AC | Criterion | Test cases | Bugs found |",
  "|---|---|---|---|",
  ...[...acs.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([id, e]) =>
    `| ${id} | ${e.text} | ${e.cases.join(", ")} | ${[...e.bugs].sort().join(", ") || "none"} |`),
  "",
  "## Test cases",
  "",
  `| Case | Test | Layer · priority | AC | Requirement | Bug · evidence | main | ${fixes ? "fixes |" : ""}`,
  `|---|---|---|---|---|---|---|${fixes ? "---|" : ""}`,
  ...rows.map(([key, r]) => {
    const layer = r.tags.find((t) => t === "@ui" || t === "@api")?.slice(1) ?? "";
    const prio = r.tags.find((t) => /^@P\d$/.test(t))?.slice(1) ?? "";
    const acIds = (r.meta.ac ?? "").split(" | ").map((p) => p.split(":")[0]).join(", ");
    const fx = fixes ? ` ${mark(fixes.rows.get(key)?.status ?? "not run")} |` : "";
    return `| ${key} | ${r.title.replace(/\|/g, "\\|")} <br/><sub>\`tests/${r.file}\`</sub> | ${layer} · ${prio} | ${acIds} | ${r.meta.requirement ?? ""} | ${bugCell(r)} | ${mark(r.status)} |${fx}`;
  }),
  "",
];

writeFileSync(join(ROOT, "docs", "TRACEABILITY.md"), lines.join("\n"));
console.log(`docs/TRACEABILITY.md: ${rows.length} cases, ${acs.size} acceptance criteria`);
